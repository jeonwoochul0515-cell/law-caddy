export interface ContractData {
  caseData: Case;
  user: User;
  fees: ContractFees;
}

/** 수임계약서 + 개인정보동의서 텍스트 자동 생성 */
export function generateContractText(data: ContractData): string {
  const { caseData, user, fees } = data;
  const isCriminal = caseData.caseType === "형사";

  const contractBody = isCriminal
    ? buildCriminalContract(caseData, user, fees)
    : buildCivilContract(caseData, user, fees);

  const privacyConsent = buildPrivacyConsent(user.firmName);

  return contractBody + "\n\n" + privacyConsent;
}

